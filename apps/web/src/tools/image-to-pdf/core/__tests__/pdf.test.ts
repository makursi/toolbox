import { describe, expect, it } from "vitest";

import { pageGeometry, type PageGeometry } from "@/tools/image-to-pdf/core/geometry";
import type { ExifOrientation } from "@/tools/image-to-pdf/core/orientation";
import { buildPdf, type PdfImage, type PdfPage } from "@/tools/image-to-pdf/core/pdf";

/**
 * The PDF writer's structural invariants. A reader that cannot follow the xref
 * table will not open the file at all, so these assert the properties a reader
 * relies on rather than a golden byte string: every offset resolves to its own
 * object header, the page tree's `/Count` is the number of pages, each stream's
 * declared `/Length` is exactly its data, and each `/MediaBox` is the chosen
 * paper's box.
 *
 * The bytes are parsed here, not compared to a fixture. A golden string would
 * have to be regenerated by the thing it is checking.
 */

const PDF_HEADER = "%PDF-1.7\n";

function latin1(bytes: Uint8Array): string {
  return Buffer.from(bytes).toString("latin1");
}

type ObjectSlice = { number: number; offset: number; text: string };

type InspectedPdf = {
  bytes: Uint8Array;
  text: string;
  xrefOffset: number;
  objects: ObjectSlice[];
  trailer: string;
};

/**
 * Read the file the way a reader does: `startxref` -> xref table -> each
 * object's byte offset -> its header, then the trailer. Throws with a sentence
 * when a step does not resolve, which is exactly the failure that makes a PDF
 * unopenable.
 */
function inspectPdf(bytes: Uint8Array): InspectedPdf {
  const text = latin1(bytes);
  const startxref = text.lastIndexOf("startxref");
  if (startxref === -1) throw new Error("the file has no startxref");

  const tail = text.slice(startxref + "startxref".length).trimStart();
  const match = /^(\d+)/.exec(tail);
  if (match === null) throw new Error("startxref names no offset");
  const xrefOffset = Number(match[1]);

  if (!text.startsWith("xref", xrefOffset)) {
    throw new Error(`the xref offset ${xrefOffset} does not point at an xref table`);
  }

  const xrefText = text.slice(xrefOffset);
  const header = /^xref\n0 (\d+)\n/.exec(xrefText);
  if (header === null) throw new Error("the xref table has no 0 subsection header");
  const entryCount = Number(header[1]);

  const entriesStart = xrefOffset + header[0].length;
  const entries = xrefText.slice(header[0].length).split("\n");
  const offsets: number[] = [];

  for (let number = 0; number < entryCount; number += 1) {
    const entry = entries[number];
    if (entry === undefined || !/^\d{10} \d{5} [nf] ?$/.test(entry)) {
      throw new Error(`xref entry ${number} is malformed: ${String(entry)}`);
    }
    offsets[number] = Number(entry.slice(0, 10));
  }

  const trailer = text.slice(entriesStart + entries.slice(0, entryCount).join("\n").length);

  const objects: ObjectSlice[] = [];
  for (let number = 1; number < entryCount; number += 1) {
    const offset = offsets[number];
    if (offset === undefined) throw new Error(`object ${number} has no xref entry`);
    if (!text.startsWith(`${number} 0 obj`, offset)) {
      throw new Error(`the xref offset for object ${number} does not point at its header`);
    }
    objects.push({ number, offset, text: "" });
  }

  // oxlint-disable-next-line unicorn/no-array-sort -- the project's lib target is ES2022, so `toSorted` is not in the standard library this test compiles against.
  const bounds = [...objects.map((object) => object.offset), xrefOffset].sort(
    (left, right) => left - right,
  );
  for (const object of objects) {
    const end = bounds[bounds.indexOf(object.offset) + 1] ?? xrefOffset;
    object.text = text.slice(object.offset, end);
  }

  return { bytes, text, xrefOffset, objects, trailer };
}

/** The data between `stream\n` and `\nendstream`, read through the declared `/Length`. */
function streamData(
  inspected: InspectedPdf,
  object: ObjectSlice,
): { declared: number; data: Uint8Array; terminated: boolean } {
  const length = /\/Length (\d+)/.exec(object.text);
  if (length === null) throw new Error(`object ${object.number} declares no /Length`);
  const declared = Number(length[1]);

  const streamAt = object.text.indexOf("stream\n");
  if (streamAt === -1) throw new Error(`object ${object.number} has no stream`);
  const dataStart = object.offset + streamAt + "stream\n".length;
  const data = inspected.bytes.slice(dataStart, dataStart + declared);
  const after = latin1(inspected.bytes.slice(dataStart + declared, dataStart + declared + 11));

  return { declared, data, terminated: after.startsWith("\nendstream") };
}

function jpegSource(
  channels: 1 | 3 | 4,
  dimensions = { width: 600, height: 800 },
  orientation: ExifOrientation = 1,
): PdfImage {
  // The writer copies these bytes; it never looks inside them. A little
  // container-shaped byte string is enough to prove the copy.
  return {
    kind: "jpeg",
    bytes: new Uint8Array([0xff, 0xd8, 0x12, 0x34, 0x56, 0xff, 0xd9]),
    width: dimensions.width,
    height: dimensions.height,
    channels,
    orientation,
  };
}

/**
 * A page whose image is packed RGB samples: what a PNG, a WebP or a decoded
 * JPEG becomes after the browser decodes it (`core/packing.ts`). The bytes here
 * stand for the zlib-wrapped stream; the writer copies them like it copies a
 * JPEG. A decoded image arrives upright, so its type carries no orientation.
 */
function rawSource(dimensions = { width: 600, height: 800 }): PdfImage {
  return {
    kind: "raw-rgb",
    bytes: new Uint8Array([0x78, 0x9c, 0x03, 0x00, 0x00, 0x00, 0x00, 0x01]),
    width: dimensions.width,
    height: dimensions.height,
  };
}

function page(paper: "a4" | "letter", image = jpegSource(3)): PdfPage {
  return {
    geometry: pageGeometry(
      { width: image.width, height: image.height },
      paper,
      image.kind === "jpeg" ? image.orientation : 1,
    ),
    image,
  };
}

/** The one `cm` matrix in the file's content streams, as six numbers. */
function contentMatrices(text: string): number[][] {
  return [...text.matchAll(/q\n([-\d. ]+) cm\n\/Im0 Do\nQ/g)].map((match) =>
    (match[1] ?? "").trim().split(/\s+/).map(Number),
  );
}

describe("the PDF writer", () => {
  it("writes a preamble, a binary comment line and an end-of-file marker", () => {
    const bytes = buildPdf([page("a4")]);
    const text = latin1(bytes);

    expect(text.startsWith(PDF_HEADER)).toBe(true);

    // The binary comment line is what makes a transfer treat the file as binary
    // rather than as text; four bytes with the high bit set is the convention.
    const comment = bytes.slice(PDF_HEADER.length, PDF_HEADER.length + 5);
    expect(latin1(comment.slice(0, 1))).toBe("%");
    for (const byte of comment.slice(1)) expect(byte).toBeGreaterThan(127);

    expect(text.endsWith("%%EOF\n")).toBe(true);
  });

  it("writes one page object, one content stream and one image XObject per page", () => {
    const bytes = buildPdf([page("a4"), page("letter")]);
    const inspected = inspectPdf(bytes);
    const text = inspected.text;

    expect(text.match(/\/Type \/Page\b/g)).toHaveLength(2);
    expect(text.match(/\/Subtype \/Image/g)).toHaveLength(2);
    expect(text.match(/\/Contents \d+ 0 R/g)).toHaveLength(2);
    // Two pages, three objects each, plus the catalog and the page tree.
    expect(inspected.objects).toHaveLength(2 + 2 * 3);
  });

  it("agrees with its own page tree: /Count equals the number of kids", () => {
    const inspected = inspectPdf(buildPdf([page("a4"), page("a4"), page("a4")]));

    expect(inspected.text).toMatch(/\/Type \/Pages \/Count 3/);
    const kids = /\/Kids \[([^\]]*)\]/.exec(inspected.text);
    expect(kids).not.toBeNull();
    expect(kids?.[1]?.match(/\d+ 0 R/g) ?? []).toHaveLength(3);
  });

  it("points every xref offset at its own object header", () => {
    // `inspectPdf` throws when an offset does not resolve; asserting the parsed
    // count is what keeps the helper from passing on an empty table.
    const inspected = inspectPdf(buildPdf([page("a4"), page("letter")]));

    expect(inspected.objects.map((object) => object.number)).toEqual([1, 2, 3, 4, 5, 6, 7, 8]);
    for (const object of inspected.objects) {
      expect(inspected.text.startsWith(`${object.number} 0 obj`, object.offset)).toBe(true);
    }
  });

  it("declares the exact /Length of every stream", () => {
    const inspected = inspectPdf(
      buildPdf([page("a4"), page("letter", jpegSource(3, { width: 1600, height: 900 }))]),
    );

    const streams = inspected.objects.filter((object) => object.text.includes("\nstream\n"));
    expect(streams).toHaveLength(4);

    for (const object of streams) {
      const { data, terminated } = streamData(inspected, object);
      expect(data.byteLength, `object ${object.number}`).toBeGreaterThan(0);
      // The declared length must land exactly on the endstream marker: one byte
      // more or less is a file a reader cannot parse.
      expect(terminated, `object ${object.number}`).toBe(true);
    }
  });

  it("writes the chosen paper into each /MediaBox, in the image's orientation", () => {
    const inspected = inspectPdf(
      buildPdf([
        page("a4", jpegSource(3, { width: 600, height: 800 })),
        page("a4", jpegSource(3, { width: 1600, height: 900 })),
        page("letter", jpegSource(3, { width: 600, height: 800 })),
      ]),
    );

    const boxes = [...inspected.text.matchAll(/\/MediaBox \[0 0 ([\d.]+) ([\d.]+)\]/g)].map(
      (match) => [Number(match[1]), Number(match[2])] as const,
    );

    expect(boxes).toHaveLength(3);
    expect(boxes[0]?.[0]).toBeCloseTo(595.28, 4);
    expect(boxes[0]?.[1]).toBeCloseTo(841.89, 4);
    expect(boxes[1]?.[0]).toBeCloseTo(841.89, 4);
    expect(boxes[1]?.[1]).toBeCloseTo(595.28, 4);
    expect(boxes[2]?.[0]).toBeCloseTo(612, 4);
    expect(boxes[2]?.[1]).toBeCloseTo(792, 4);
  });

  it("copies the JPEG bytes verbatim into a DCTDecode image stream", () => {
    const image = jpegSource(3);
    const inspected = inspectPdf(buildPdf([{ geometry: pageGeometry(image, "a4"), image }]));
    const object = inspected.objects.find((one) => one.text.includes("/Subtype /Image"));

    expect(object).toBeDefined();
    expect(object?.text).toContain("/Filter /DCTDecode");
    expect(object?.text).toContain("/ColorSpace /DeviceRGB");
    expect(object?.text).toContain("/BitsPerComponent 8");
    expect(object?.text).toContain(`/Width ${image.width}`);
    expect(object?.text).toContain(`/Height ${image.height}`);

    const { data } = streamData(inspected, object!);
    expect([...data]).toEqual([...image.bytes]);
  });

  it("derives the colour space from the channel count", () => {
    const gray = inspectPdf(
      buildPdf([
        { geometry: pageGeometry({ width: 600, height: 800 }, "a4"), image: jpegSource(1) },
      ]),
    );
    const grayImage = gray.objects.find((one) => one.text.includes("/Subtype /Image"));
    expect(grayImage?.text).toContain("/ColorSpace /DeviceGray");

    const cmyk = inspectPdf(
      buildPdf([
        { geometry: pageGeometry({ width: 600, height: 800 }, "a4"), image: jpegSource(4) },
      ]),
    );
    const cmykImage = cmyk.objects.find((one) => one.text.includes("/Subtype /Image"));
    expect(cmykImage?.text).toContain("/ColorSpace /DeviceCMYK");
    // PDF's DeviceCMYK is the inverted convention; omitting /Decode prints
    // every CMYK JPEG with inverted ink.
    expect(cmykImage?.text).toContain("/Decode [1 0 1 0 1 0 1 0]");
  });

  it("writes raw samples as DeviceRGB through FlateDecode, with no predictor", () => {
    const image = rawSource();
    const inspected = inspectPdf(buildPdf([{ geometry: pageGeometry(image, "a4"), image }]));
    const object = inspected.objects.find((one) => one.text.includes("/Subtype /Image"));

    expect(object).toBeDefined();
    expect(object?.text).toContain("/ColorSpace /DeviceRGB");
    expect(object?.text).toContain("/BitsPerComponent 8");
    expect(object?.text).toContain("/Filter /FlateDecode");
    expect(object?.text).toContain(`/Width ${image.width}`);
    expect(object?.text).toContain(`/Height ${image.height}`);

    // The samples are written exactly as they arrived: zlib-wrapped RGB, not
    // re-encoded and not passed through a PNG predictor. `docs/adr/0020` says no
    // `/DecodeParms` precisely so no reader has to agree about a predictor.
    expect(object?.text).not.toContain("/DecodeParms");
    expect(object?.text).not.toContain("/DCTDecode");

    const { data } = streamData(inspected, object!);
    expect([...data]).toEqual([...image.bytes]);
  });

  it("gives a raw-samples page the same geometry a JPEG of those dimensions gets", () => {
    // PNG and WebP are pages, not a second geometry: the same pixel dimensions
    // and paper must produce the same media box and the same placement matrix
    // as the passthrough path. Both readings are pulled from the files.
    for (const dimensions of [
      { width: 600, height: 800 },
      { width: 1600, height: 900 },
    ]) {
      for (const paper of ["a4", "letter"] as const) {
        const jpegPage = {
          geometry: pageGeometry(dimensions, paper),
          image: jpegSource(3, dimensions),
        };
        const rawPage = { geometry: pageGeometry(dimensions, paper), image: rawSource(dimensions) };

        const jpegText = latin1(buildPdf([jpegPage]));
        const rawText = latin1(buildPdf([rawPage]));

        const box = (text: string) => /\/MediaBox \[0 0 [\d.]+ [\d.]+\]/.exec(text)?.[0];
        const matrix = (text: string) =>
          /q\n[\d.]+ 0 0 [\d.]+ [\d.]+ [\d.]+ cm\n\/Im0 Do\nQ/.exec(text)?.[0];

        expect(
          box(rawText),
          `${String(dimensions.width)}x${String(dimensions.height)} ${paper}`,
        ).toBe(box(jpegText));
        expect(
          matrix(rawText),
          `${String(dimensions.width)}x${String(dimensions.height)} ${paper}`,
        ).toBe(matrix(jpegText));
      }
    }
  });

  it("places the image with the rectangle the geometry function produced", () => {
    const geometry = pageGeometry({ width: 600, height: 800 }, "a4");
    const inspected = inspectPdf(buildPdf([{ geometry, image: jpegSource(3) }]));
    const content = inspected.objects.find((one) => one.text.includes(" cm\n/Im0 Do"));

    // The content stream draws one image through one matrix, at the geometry
    // rectangle's size and position.
    const matrix = /q\n([\d.]+) 0 0 ([\d.]+) ([\d.]+) ([\d.]+) cm\n\/Im0 Do\nQ/.exec(
      content?.text ?? "",
    );
    expect(matrix).not.toBeNull();
    expect(Number(matrix?.[1])).toBeCloseTo(geometry.image.width, 3);
    expect(Number(matrix?.[2])).toBeCloseTo(geometry.image.height, 3);
    expect(Number(matrix?.[3])).toBeCloseTo(geometry.image.x, 3);
    expect(Number(matrix?.[4])).toBeCloseTo(geometry.image.y, 3);
  });

  /*
   * EXIF orientation is a placement, not a pixel operation: the JPEG's bytes are
   * copied untouched (asserted above) and the turn lives in the content stream,
   * so no generation is spent making a portrait photo upright. The rectangle is
   * fixed here and the expected matrices are worked out from the orientation
   * table by hand, one row per value; a negative scale is what the mirrored
   * values cost.
   */
  it("turns the image in the content stream for every EXIF orientation", () => {
    const rectangle: PageGeometry = {
      page: { width: 200, height: 100 },
      image: { x: 10, y: 20, width: 80, height: 40 },
    };

    const expected: Record<ExifOrientation, number[]> = {
      1: [80, 0, 0, 40, 10, 20],
      2: [-80, 0, 0, 40, 90, 20],
      3: [-80, 0, 0, -40, 90, 60],
      4: [80, 0, 0, -40, 10, 60],
      5: [0, -40, -80, 0, 90, 60],
      6: [0, -40, 80, 0, 10, 60],
      7: [0, 40, 80, 0, 10, 20],
      8: [0, 40, -80, 0, 90, 20],
    };

    for (const orientation of [1, 2, 3, 4, 5, 6, 7, 8] as const) {
      const text = latin1(
        buildPdf([
          { geometry: rectangle, image: jpegSource(3, { width: 80, height: 40 }, orientation) },
        ]),
      );

      expect(contentMatrices(text)[0], `orientation ${String(orientation)}`).toEqual(
        expected[orientation],
      );
    }
  });

  it("writes a turned picture onto the page the geometry function laid out for it", () => {
    // A 96 x 128 photo tagged value 6 is viewed as 128 x 96: A4 is used
    // sideways, and the matrix is the quarter turn inside that box.
    const stored = { width: 96, height: 128 };
    const geometry = pageGeometry(stored, "a4", 6);
    const inspected = inspectPdf(buildPdf([{ geometry, image: jpegSource(3, stored, 6) }]));

    const box = /\/MediaBox \[0 0 ([\d.]+) ([\d.]+)\]/.exec(inspected.text);
    expect(Number(box?.[1])).toBeCloseTo(841.89, 2);
    expect(Number(box?.[2])).toBeCloseTo(595.28, 2);

    const [a, b, c, d, e, f] = contentMatrices(inspected.text)[0] ?? [];
    // The image fills the page's height, is centred across its width, and is
    // turned a quarter clockwise through the negative b and the positive c.
    expect(a).toBeCloseTo(0, 6);
    expect(b).toBeCloseTo(-geometry.image.height, 3);
    expect(c).toBeCloseTo(geometry.image.width, 3);
    expect(d).toBeCloseTo(0, 6);
    expect(e).toBeCloseTo(geometry.image.x, 3);
    expect(f).toBeCloseTo(geometry.image.y + geometry.image.height, 3);
  });

  it("points the trailer at the catalog and every page at the page tree", () => {
    const inspected = inspectPdf(buildPdf([page("a4")]));

    expect(inspected.trailer).toMatch(/trailer/);
    expect(inspected.trailer).toMatch(/\/Size 6/);
    expect(inspected.trailer).toMatch(/\/Root 1 0 R/);
    expect(inspected.text).toContain("/Type /Catalog /Pages 2 0 R");
    expect(inspected.text).toContain("/Type /Page /Parent 2 0 R");
  });
});
